"""Parser and analyzer for Quantum ESPRESSO dos.x output files."""

from pydantic import BaseModel, ConfigDict, Field


class DOSData(BaseModel):
    """Parsed Electronic Density of States shifted or raw."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    fermi_energy_ev: float | None = None
    energies_ev: list[float] = Field(default_factory=list)
    dos_states_per_ev: list[float] = Field(default_factory=list)
    integrated_dos_electrons: list[float] = Field(default_factory=list)


def parse_qe_dos_file(text: str) -> DOSData:
    """Parse a standard pwscf.dos text file generated by dos.x."""
    fermi_ev: float | None = None
    energies: list[float] = []
    dos_vals: list[float] = []
    int_dos: list[float] = []

    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            if "EFermi" in stripped and "=" in stripped:
                parts = stripped.split("EFermi")[-1].replace("=", " ").split()
                if parts:
                    try:
                        fermi_ev = float(parts[0])
                    except ValueError:
                        pass
            continue
        cols = [float(x) for x in stripped.split()]
        if len(cols) >= 3:
            energies.append(cols[0])
            dos_vals.append(cols[1])
            int_dos.append(cols[2])

    return DOSData(
        fermi_energy_ev=fermi_ev,
        energies_ev=energies,
        dos_states_per_ev=dos_vals,
        integrated_dos_electrons=int_dos,
    )
